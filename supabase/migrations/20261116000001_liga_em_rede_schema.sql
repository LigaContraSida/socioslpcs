-- =============================================================================
-- LIGA EM REDE — Liga Portuguesa Contra a SIDA (LPCS)
-- Esquema Oficial PostgreSQL / Supabase (Sócios, Parceiros, Quotas e Protocolos)
-- =============================================================================

-- 1. Associados e Administradores (users)
CREATE TABLE IF NOT EXISTS public.users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  salt TEXT NOT NULL,
  birth_date DATE NOT NULL,
  address TEXT NOT NULL,
  postal_code TEXT NOT NULL,
  city TEXT NOT NULL,
  nif TEXT NOT NULL UNIQUE,
  phone TEXT NOT NULL,
  member_number TEXT NOT NULL UNIQUE,
  is_admin BOOLEAN NOT NULL DEFAULT FALSE,
  is_suspended BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. Sessões de Associados (sessions)
CREATE TABLE IF NOT EXISTS public.sessions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  token TEXT NOT NULL UNIQUE,
  expires_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 3. Quotas Anuais / Semestrais (quotas)
CREATE TABLE IF NOT EXISTS public.quotas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  plan_type TEXT NOT NULL, -- 'anual' | 'semestral' | 'solidaria'
  amount_cents INTEGER NOT NULL,
  payment_method TEXT NOT NULL, -- 'mbway' | 'multibanco' | 'transferencia'
  reference TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'pago', -- 'pendente' | 'pago'
  valid_from DATE NOT NULL,
  valid_until DATE NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 4. Recibos e Comprovativos de Quota (receipts)
CREATE TABLE IF NOT EXISTS public.receipts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  quota_id BIGINT REFERENCES public.quotas(id) ON DELETE SET NULL,
  original_name TEXT NOT NULL,
  mime_type TEXT NOT NULL,
  file_size INTEGER NOT NULL,
  file_base64 TEXT,
  storage_path TEXT,
  notes TEXT,
  uploaded_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 5. Entidades Parceiras e Protocolos (partners)
CREATE TABLE IF NOT EXISTS public.partners (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  category TEXT NOT NULL,
  description TEXT NOT NULL,
  area TEXT NOT NULL,
  district TEXT NOT NULL,
  city TEXT NOT NULL,
  benefit_type TEXT NOT NULL, -- 'cupao' | 'codigo' | 'voucher'
  benefit_value TEXT NOT NULL,
  discount_highlight TEXT NOT NULL,
  usage_limit TEXT NOT NULL,
  max_uses INTEGER,
  code_mode TEXT NOT NULL DEFAULT 'rotativo', -- 'rotativo' | 'codigo_unico'
  estimated_annual_savings NUMERIC(10, 2) NOT NULL DEFAULT 50.00,
  valid_until DATE NOT NULL DEFAULT '2027-12-31',
  terms TEXT NOT NULL,
  website TEXT,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  secret_code TEXT NOT NULL,
  logo_mime TEXT,
  logo_base64 TEXT,
  logo_storage_path TEXT,
  nif TEXT,
  address TEXT,
  contact_name TEXT,
  contact_role TEXT,
  protocol_duration TEXT NOT NULL DEFAULT 'um ano',
  signed_protocol_name TEXT,
  signed_protocol_mime TEXT,
  signed_protocol_base64 TEXT,
  signed_protocol_storage_path TEXT,
  signed_protocol_uploaded_at TIMESTAMPTZ,
  counter_signed_protocol_name TEXT,
  counter_signed_protocol_mime TEXT,
  counter_signed_protocol_base64 TEXT,
  counter_signed_protocol_storage_path TEXT,
  counter_signed_protocol_uploaded_at TIMESTAMPTZ,
  protocol_in_force BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 6. Imagens Ilustrativas dos Serviços dos Parceiros (partner_images)
CREATE TABLE IF NOT EXISTS public.partner_images (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  partner_id BIGINT NOT NULL REFERENCES public.partners(id) ON DELETE CASCADE,
  original_name TEXT NOT NULL,
  mime_type TEXT NOT NULL,
  file_size INTEGER NOT NULL,
  file_base64 TEXT,
  storage_path TEXT,
  caption TEXT,
  sort_order INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 7. Contas de Acesso à Área Privada de Parceiros (partner_accounts)
CREATE TABLE IF NOT EXISTS public.partner_accounts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  partner_id BIGINT NOT NULL UNIQUE REFERENCES public.partners(id) ON DELETE CASCADE,
  email TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  salt TEXT NOT NULL,
  contact_name TEXT,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 8. Sessões de Parceiros (partner_sessions)
CREATE TABLE IF NOT EXISTS public.partner_sessions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  partner_account_id BIGINT NOT NULL REFERENCES public.partner_accounts(id) ON DELETE CASCADE,
  token TEXT NOT NULL UNIQUE,
  expires_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 9. Propostas de Parceria Empresarial (partner_inquiries)
CREATE TABLE IF NOT EXISTS public.partner_inquiries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_name TEXT NOT NULL,
  nif TEXT,
  address TEXT,
  contact_name TEXT NOT NULL,
  contact_role TEXT,
  email TEXT NOT NULL,
  phone TEXT NOT NULL,
  area TEXT NOT NULL,
  district TEXT NOT NULL,
  city TEXT NOT NULL,
  benefit_type TEXT NOT NULL,
  proposed_benefit TEXT NOT NULL,
  protocol_duration TEXT NOT NULL DEFAULT 'um ano',
  valid_until DATE NOT NULL DEFAULT '2027-12-31',
  max_uses INTEGER,
  code_mode TEXT NOT NULL DEFAULT 'rotativo',
  proposed_code TEXT,
  website TEXT,
  notes TEXT,
  logo_name TEXT,
  logo_mime TEXT,
  logo_base64 TEXT,
  signed_protocol_name TEXT,
  signed_protocol_mime TEXT,
  signed_protocol_base64 TEXT,
  signed_protocol_uploaded_at TIMESTAMPTZ,
  counter_signed_protocol_name TEXT,
  counter_signed_protocol_mime TEXT,
  counter_signed_protocol_base64 TEXT,
  counter_signed_protocol_uploaded_at TIMESTAMPTZ,
  status TEXT NOT NULL DEFAULT 'pendente', -- 'pendente' | 'em_analise' | 'aprovada' | 'recusada'
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 10. Imagens de Propostas de Parceria (partner_inquiry_images)
CREATE TABLE IF NOT EXISTS public.partner_inquiry_images (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  inquiry_id BIGINT NOT NULL REFERENCES public.partner_inquiries(id) ON DELETE CASCADE,
  original_name TEXT NOT NULL,
  mime_type TEXT NOT NULL,
  file_size INTEGER NOT NULL,
  file_base64 TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 11. Emissão e Validação de Códigos de Desconto (redemptions)
CREATE TABLE IF NOT EXISTS public.redemptions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  partner_id BIGINT NOT NULL REFERENCES public.partners(id) ON DELETE CASCADE,
  user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  secret_salt TEXT NOT NULL,
  reference_code TEXT NOT NULL UNIQUE,
  issued_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  expires_at TIMESTAMPTZ NOT NULL,
  status TEXT NOT NULL DEFAULT 'active', -- 'active' | 'used' | 'expired'
  used_at TIMESTAMPTZ,
  used_by_merchant TEXT
);

-- 12. Registo de Auditoria RGPD (audit_logs)
CREATE TABLE IF NOT EXISTS public.audit_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
  action TEXT NOT NULL,
  details TEXT NOT NULL,
  ip_address TEXT,
  user_agent TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 13. Notificações Institucionais de E-mail (email_notifications)
CREATE TABLE IF NOT EXISTS public.email_notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  recipient TEXT NOT NULL DEFAULT 'info@ligacontrasida.org',
  event_type TEXT NOT NULL,
  subject TEXT NOT NULL,
  body_text TEXT NOT NULL,
  body_html TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'registado',
  error_message TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Índices de Desempenho
CREATE INDEX IF NOT EXISTS idx_sessions_token ON public.sessions(token);
CREATE INDEX IF NOT EXISTS idx_partner_sessions_token ON public.partner_sessions(token);
CREATE INDEX IF NOT EXISTS idx_quotas_user ON public.quotas(user_id);
CREATE INDEX IF NOT EXISTS idx_receipts_user ON public.receipts(user_id);
CREATE INDEX IF NOT EXISTS idx_redemptions_ref ON public.redemptions(reference_code);
CREATE INDEX IF NOT EXISTS idx_redemptions_user_partner ON public.redemptions(user_id, partner_id);
CREATE INDEX IF NOT EXISTS idx_partner_images_partner ON public.partner_images(partner_id);
CREATE INDEX IF NOT EXISTS idx_partner_inquiry_images_inq ON public.partner_inquiry_images(inquiry_id);

